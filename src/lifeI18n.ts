export function useLifeLanguage() {
  const base = useLanguage();
  const l = base.language === 'ru' ? ru : en;
  const money = (amount: number) =>
    new Intl.NumberFormat(base.locale, {
      style: 'currency',
      currency: 'USD',
      maximumFractionDigits: 2,
    }).format(amount);
  const number = (value: number) =>
    new Intl.NumberFormat(base.locale, { maximumFractionDigits: 1 }).format(value);
  const duration = (hours: number) => {
    const minutes = Math.round(hours * 60);
    return base.language === 'ru'
      ? `${Math.floor(minutes / 60)} ч ${minutes % 60} мин`
      : `${Math.floor(minutes / 60)}h ${String(minutes % 60).padStart(2, '0')}m`;
  };
  return { ...base, l, money, number, duration };
}
